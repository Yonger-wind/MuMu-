export function loadBuiltinScripts() {
  const list = [];
  for (const s of SOURCES) {
    try {
      const sc = parseScriptText(s.text, s.id);
      sc.id = s.id;
      sc.builtin = true;
      sc.tag = s.tag;
      list.push(sc);
    } catch (e) {
      console.error('内置剧本解析失败', s.id, e);
    }
  }
  return list;
}
