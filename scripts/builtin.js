玛格丽特：同样是深蓝的夜空、燃烧般的柏树、宁静的村庄和明亮的星辰。但只要你仔细看，就会发现一件让人毛骨悚然的事——
玛格丽特：画中夜空里所有星云漩涡的旋转方向，与世人熟知的那幅《星月夜》，恰好完全相反。
卢卡斯（瞳孔骤缩，低声）：逆向的漩涡……这在艺术史上几乎是不可能的。
卢卡斯：右撇子画家在情绪极度亢奋时挥笔，手腕的肌肉记忆和运笔弧度是固定的。除非他故意用左手作画，或者……他当时正对着一面镜子，描绘自己的幻觉。
克莱尔（敏锐地抓住重点）：那幅画后来去了哪里？为什么会牵扯到亨利和索菲娅？
玛格丽特（露出一丝苦笑）：祖父认为那批遗物牵扯到疗养院一些不光彩的往事，一直秘而不宣。
玛格丽特：直到五年前，庄园面临巨额修缮税款，我不得不委托亨利帮忙秘密评估几件祖传古董。结果，被他无意中发现了这幅画的存在。
玛格丽特：从那天起，贪婪就像藤蔓一样，缠上了这里。
起居室的侧门被轻轻推开，埃莱娜·罗西走了进来。她梳着一丝不苟的低马尾，穿着朴素的藏青色针织衫，怀里紧紧抱着一个厚实的牛皮纸档案袋。
埃莱娜：德拉图尔女士，您让我整理的一八八九年圣雷米捐赠与病历副本，我已经带来了。
埃莱娜：不过，我必须提醒您——一旦这些文件离开庄园，很多人的名字，就再也藏不住了。
克莱尔（看向她）：这位是？
玛格丽特：埃莱娜·罗西，圣雷米地区档案室的资深管理员，也是我家族多年的朋友。
埃莱娜（将牛皮纸档案袋放在茶几上）：圣雷米档案室的绝大多数公开记录，在八十年代就已经移交给了省立档案馆。
埃莱娜：但有一份关于“夜间观察日记”的原始副本，因为涉及当时几位本地士绅的隐私，一直保存在庄园的地下室里。
埃莱娜：亨利·莫罗上个月来找过我两次，开出一张足以让我后半生衣食无忧的支票，想买走它。我拒绝了。
卢卡斯正准备伸手去翻看档案袋，庭院外突然传来急促的引擎声与刹车声。
朱利安大步跨进起居室，身后跟着两名神情严肃的法国警员，卡其色风衣的衣摆随着动作剧烈晃动。
朱利安（目光冷冽地扫过茶几）：看来巴黎的空气确实不适合养病。两位一早就跑到普罗旺斯来呼吸新鲜空气了？
朱利安：温莎小姐，范·登·伯格先生，我记得我昨晚说过，在案情明朗之前，希望两位留在巴黎配合调查。
克莱尔（神色不变，语气从容）：勒克莱尔探员，我们只是来向德拉图尔女士核实一件与莫罗先生生前交易相关的艺术品背景。
克莱尔：相反，您这么快就从巴黎赶到普罗旺斯，难道案子已经有了突破性进展？
朱利安（双手撑在茶几边缘，压低声音）：莫罗案的初步尸检报告和物证分析，今天凌晨出来了。
朱利安：凶器是一根带有黄铜配重的专业画架固定杆，上面没有提取到任何有效指纹，因为凶手戴着手套。
朱利安：更有趣的是，沙龙走廊的监控系统在案发前五分钟被人用动态循环代码接管了，手法极其专业。
朱利安：而我们在巴黎外围监控里发现，一个有前科的前画廊技工，昨晚就出现在沙龙附近。
卢卡斯心中一凛，脑海里瞬间浮现出昨晚在楼梯口看到的那个炭灰色连帽卫衣身影。
就在气氛剑拔弩张之际，庭院外的石子路上又驶来一辆线条冷硬的黑色豪华轿车。
索菲娅迈步走下，今天换了一套剪裁更利落的墨绿色西装套裙，在普罗旺斯明媚的阳光下泛着冷冽而高傲的光泽。她径直走进起居室，仿佛完全无视在场的警察，目光直接锁定了茶几上的牛皮纸档案袋。
索菲娅（嘴角带着居高临下的微笑）：各位聚在这里，是在开一场关于《星月夜》的私人研讨会吗？真遗憾没有通知我。
索菲娅：不过没关系。我今天来，是想提出一个很简单的商业提议——无论你们手里掌握着关于那幅“逆向星月夜”的什么文件，我出双倍的价格，现在就买下它。
朱利安（眉头紧锁，转身盯着她）：科瓦列夫斯卡娅女士，您现在已经是莫罗谋杀案的重要关系人。我劝您注意言辞，不要试图用金钱干扰刑事调查。
索菲娅（轻笑一声，眼神冰冷如刀）：探员先生，我只是在谈艺术品投资，这在法国并不违法。
索菲娅：至于亨利·莫罗的死……一个连自己藏品都看不住的蠢货，死了对整个艺术圈来说，未尝不是一种净化。
起居室里的空气仿佛被彻底点燃。玛格丽特脸色惨白地靠在椅背上，埃莱娜死死按住茶几上的档案袋，朱利安的手已经按在了腰间的配枪套上。
卢卡斯与克莱尔交换了一个极其隐蔽的眼神——他们都清楚，真正的博弈，现在才刚刚拉开帷幕。

【镜头：中景】
埃莱娜的档案可能揭开百年前疗养院被掩盖的真相；而索菲娅在尼斯海岸的私人画库里，极可能藏着那幅“逆向漩涡”的实物，以及亨利·莫罗洗钱走私的核心账本。
