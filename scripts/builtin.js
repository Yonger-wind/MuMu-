【场景：地下室 | 白天 | 中景】
楼上起居室里，朱利安正严厉质问索菲娅出现在普罗旺斯的动机，争执声隔着厚重的胡桃木地板传下来，显得沉闷而遥远。
趁着楼上气氛剑拔弩张，埃莱娜迅速抱起茶几上的档案袋，向卢卡斯与克莱尔使了一个极其隐蔽的眼色。三人悄无声息地穿过走廊尽头的酒窖暗门，沿着狭窄陡峭的螺旋石阶走入庄园地下室。
地下室弥漫着潮湿的石灰味、陈年橡木桶的酸涩气息与旧纸张特有的霉味。一盏昏黄的钨丝灯吊在拱形石顶中央，在斑驳的石墙上投下长短不一的晃动黑影。
角落里整齐排列着几排生锈的铁皮档案柜，柜门上贴着早已褪色的手写编号标签。
埃莱娜将牛皮纸档案袋放在一张布满划痕的胡桃木长桌上，低马尾垂在藏青色针织衫后，动作沉稳而克制。
埃莱娜：这里原本是德拉图尔家族存放契约与葡萄园账册的地方。三十年前，老德拉图尔先生把从圣雷米旧疗养院带回来的私密卷宗，锁在了最里面的那排铁柜里。
埃莱娜：这些纸页全都是十九世纪末的棉浆手工抄录，保存得还算完整。但最关键的一份《夜间观察附录》，被人撕掉了第三页。
卢卡斯从工具包里取出一副无粉白手套戴上，又拧亮一盏便携式冷光检测灯，小心翼翼地翻开泛黄脆化的纸页。
卢卡斯（低声念出法文，随后向克莱尔解释）：记录者是当年圣保罗疗养院的助理医师雷蒙·贝朗热。
卢卡斯：“一八八九年六月十八日凌晨三点，十七号病房的患者在夜间铁窗边停留极久，情绪处于一种奇异的静谧亢奋中。”
卢卡斯：“他称看见窗外的柏树像黑色的火焰一样窜上星空，星云在天幕上逆时针旋转，仿佛要把整个普罗旺斯吸进漩涡。”
克莱尔（双手抱臂）：等一下。六月十八日，正是文森特完成纽约那幅《星月夜》前后的时间。
克莱尔：可病历里为什么会写“逆时针旋转”？如果我没记错，原作里的主星云是从左向右顺时针卷动的。
埃莱娜（指尖轻轻摩挲着袖口）：继续往下看吧，温莎小姐。答案就在下一页的医生批注里。
卢卡斯屏住呼吸，用竹制书签极轻地挑起脆弱的纸角，翻过一页。纸面上的墨迹因当年的潮湿而略微晕开，字迹也比前一页更急促。
卢卡斯（声音微微发颤）：“次日清晨巡房时，患者在画架前陷入昏睡。令人震惊的是，画布上的蓝色并未呈现出他惯常使用的明艳群青，而是一种带有铅灰调的幽暗深蓝。”
卢卡斯：“所有星云的流向，都与他前一日画在草稿本上的构图完全相反。院方首席医师认为这幅画充满了不祥的‘精神镜像症’征兆，决定不将其列入患者家属领取的清单。”
卢卡斯：“而是由当时的捐助人——本地一位姓德拉图尔的绅士——秘密封存。”
【镜头：特写】
冷光检测灯的光束斜斜打在病历纸页的右下角。
卢卡斯的指尖悬停在纸页边缘一处极淡的颜料蹭痕上方。那是普鲁士蓝与铅白混合后的微弱印记，在十倍黄铜放大镜下，清晰可见细小的亚麻纤维与颗粒状矿物晶体纹理。
【镜头：中景】
卢卡斯（眼神骤然锐利）：这不是普通的墨水或印泥蹭痕。这是颜料在未完全干透时，被人用手指或画边直接按压在纸上的。
卢卡斯：也就是说，在一八八九年六月的某一天，这份病历档案，曾经和那幅“逆向星月夜”紧贴在一起过。
克莱尔（俯身盯着那道蓝灰色蹭痕）：罗西小姐，既然德拉图尔家族三十年前就已经重新发现了这批档案和画作，为什么一直没有交给国家博物馆或官方研究机构？
克莱尔：留在潮湿的地下室里，随时可能毁于霉菌或者人为篡改。
埃莱娜（抬起头，直视着克莱尔）：因为档案里被撕掉的那一页，记录着当年那场“秘密封存”背后的肮脏交易。
埃莱娜：根据我祖父留下的口信，一八八九年底，圣雷米疗养院曾爆发过一桩极其隐秘的资金挪用丑闻。
埃莱娜：几位本地名流以“资助艺术治疗”的名义侵吞了教会拨款。为了掩盖账目缺口，他们私下变卖或扣留了疗养院里几位精神病患的画作。
埃莱娜：一旦这份完整档案公开，当年参与伪造捐赠清单的几个家族，包括德拉图尔家族，都会瞬间身败名裂。
【镜头：中景】
地下室的门突然发出轻微的“吱呀”声。玛格丽特端着一只银质托盘走了下来，托盘上放着三只冒着热气的白瓷茶杯。
玛格丽特：楼上的朱利安探员已经暂时离开了，他去镇上的警局调取本地近期的车辆通行记录。
玛格丽特：至于索菲娅……我告诉她我需要时间考虑她的报价，她带着保镖暂时回圣雷米镇上的酒店去了。
玛格丽特：喝杯热红茶暖暖身子吧，地下室湿气太重了。
克莱尔接过茶杯，却没有喝，目光冷静地落在玛格丽特微颤的指尖上。
克莱尔：德拉图尔女士，那幅“逆向星月夜”的实物，现在究竟在谁手里？
克莱尔：昨晚亨利在巴黎展示的，只是一件混杂了现代钛白的伪作。真正的原作，是不是已经被您卖给了索菲娅？
玛格丽特（苦笑一声，将托盘放在档案柜顶上）：如果我已经把画卖给了她，她今天又何必亲自跑到我的庄园里来威逼利诱？
玛格丽特：五年前，索菲娅带着一笔巨额投资基金来到普罗旺斯，声称要资助圣雷米旧疗养院的数字化修复工程。那时候我确实因为庄园濒临破产，找过亨利商量变卖祖传藏品。
卢卡斯（紧盯着她的眼睛）：所以亨利不仅知道了那幅画的存在，还把消息透露给了索菲娅？
玛格丽特（点点头，眼神痛苦）：不仅如此。亨利是个天生的投机者。他从我这里骗走了画作的高清微距底片和《夜间观察附录》的副本，甚至偷偷撕走了最关键的第三页作为筹码，用来要挟当年涉事家族的后人。
玛格丽特：至于那幅画的实物……三年前，在一次从普罗旺斯运往日内瓦秘密金库的途中，运输车在山路上遭遇了诡异的劫案。画作从那以后就彻底失踪了。
克莱尔（眉头紧锁）：三年前的劫案……也就是说，亨利昨晚在巴黎展出的假画，是他在失去真迹之后，为了继续向索菲娅骗取资金而找人仿制的？
埃莱娜（突然插话）：未必只是为了骗钱。你们还记得索菲娅在巴黎沙龙说过的话吗？她说她要的不是复制品，而是“另一半”。
埃莱娜：根据档案里零星的书信记载，一八八九年六月，患者在完成那幅逆向星月夜之后，曾经用炭笔在另一张亚麻布背面画过一幅星图坐标草图。
埃莱娜：据传，那张草图指向了某种被他藏起来的私人手稿。
【镜头：特写】
卢卡斯的口袋里突然传来一阵极轻微的震动。他掏出手机，发件人是一串经过多层加密跳转的匿名号码。
短信内容只有简短的一行法文：“莫罗书房监控最后三秒已解密，凶手袖口有普罗旺斯贵族徽记刺绣。另外——真正的画在尼斯海岸。——E”
卢卡斯神色一凝，迅速将屏幕转向克莱尔。克莱尔扫了一眼，眼神瞬间冷冽如冰，随即不动声色地看了一眼身旁的玛格丽特与埃莱娜。
【镜头：中景】
克莱尔（语气平静却暗藏锋芒）：看来，有些人在巴黎和普罗旺斯之间撒下的网，比我们想象的还要大。
克莱尔：德拉图尔女士，感谢您的红茶和坦诚。我们需要回镇上取一点随身行李，晚些时候再回来继续查阅剩下的档案。
玛格丽特（微微颔首，眼神复杂）：随时欢迎。只是普罗旺斯的夜路并不太平，两位千万小心。
