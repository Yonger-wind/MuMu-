【场景：别墅 | 夜晚 | 远景】
夜幕降临，地中海沿岸的尼斯被笼罩在一片深沉的靛蓝色里。海浪拍打着陡峭的黑色礁石与防波堤，发出低沉而有节奏的轰鸣。
远离市区的一处私人海岬悬崖上，矗立着一座通体由冷灰色混凝土与巨幅防弹玻璃构建的现代主义别墅——那是索菲娅在南法的秘密行宫。
别墅二层亮着冷白色的射灯，落地窗后隐约可见几幅大型当代艺术品的抽象轮廓。

【场景：别墅 | 夜晚 | 近景】
别墅外围茂密的夹竹桃灌木阴影里，艾蒂安蹲在主配电箱与光纤接入井旁，炭灰色连帽卫衣几乎完美融入夜色。寸头上沾着细密的海雾水珠，手指在便携终端的键盘上飞快敲击。
艾蒂安（压低声音，通过骨传导耳机汇报）：外围红外对射网和草坪压力传感器，已经被我暂时旁路。核心摄像头的动态画面，也替换成了十分钟前的循环录像。
艾蒂安：但地下一层的恒温画库主门，用的是独立离线局域网，掌纹识别加十二位动态物理密钥。我最多只能在外部替你们争取到八分钟盲区。
艾蒂安：超过时间，警报就会直接连线尼斯武装安保中心。
